import {build,loadEnv} from 'vite';
import {mkdir,realpath,rm,cp,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {cloudConfiguration} from './cloud-config.mjs';
const root=fileURLToPath(new URL('..',import.meta.url));
process.env.VERTICE_DEPLOY_TARGET='cloud';
const env={...loadEnv('production',root,''),...process.env};
if(!env.ORIGIN_SECRET||Buffer.byteLength(env.ORIGIN_SECRET)<32||new Set(env.ORIGIN_SECRET).size<8)throw Error('Configure ORIGIN_SECRET forte, compartilhado com o backend.');
const config=cloudConfiguration(env);
await build({root});
const workspace=await realpath(root),parent=path.join(workspace,'.vercel');
await mkdir(parent,{recursive:true});
if(await realpath(parent)!==parent)throw Error('Diretório de saída fora do projeto.');
const output=path.join(parent,'output');
await rm(output,{recursive:true,force:true});
await mkdir(output,{recursive:true});
await cp(path.join(root,'dist'),path.join(output,'static'),{recursive:true});
await writeFile(path.join(output,'config.json'),JSON.stringify(config,null,2));
